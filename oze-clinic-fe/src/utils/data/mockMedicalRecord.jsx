const visitDate = (visitId) => VISITS.find((visit) => visit.id === visitId)?.date ?? "";

export const buildMedicalRecordData = (mode) =>
    structuredClone({
        clinic: CLINIC,
        patient: PATIENT,
        profile: PROFILE,
        upcoming: UPCOMING,
        visits: VISITS,
        plans: mode === "overdue" ? PLANS.map(withOverdue) : PLANS,
        films: FILMS,
        chart: CHART.map((entry) => ({ ...entry, date: visitDate(entry.visit) })),
        history: HISTORY,
    });

